// Bundles the MCP server, CLI and embedding process into self-contained files under mcp/dist/.
// The bundles are committed: plugins install by git clone, with no build step.
// They are minified (zod alone is ~1 MB unminified); read mcp/src instead.
// CI rebuilds and fails if the committed bundles differ from the source.
//
// mcp/dist/THIRD_PARTY_NOTICES.md is generated here too, from the packages that
// actually end up in the bundles, so their licenses travel with them.
import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const result = await build({
  entryPoints: { server: "mcp/src/bin/server.ts", cli: "mcp/src/bin/cli.ts", embedder: "mcp/src/bin/embedder.ts" },
  outdir: "mcp/dist",
  outExtension: { ".js": ".mjs" },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: true,
  legalComments: "none",
  metafile: true,
  logLevel: "info",
  banner: {
    js: [
      "// Generated by scripts/bundle.mjs from mcp/src. Do not edit.",
      "import { createRequire as __createRequire } from 'node:module';",
      "const require = __createRequire(import.meta.url);",
    ].join("\n"),
  },
});

const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (match) packages.add(match[1]);
}
const sections = [...packages].sort().map((name) => {
  const dir = join("node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licenseFile = ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "LICENCE"].find((f) => existsSync(join(dir, f)));
  const text = licenseFile ? readFileSync(join(dir, licenseFile), "utf8").trim() : `License: ${pkg.license}`;
  return `## ${name} ${pkg.version} (${pkg.license})\n\n\`\`\`\n${text}\n\`\`\``;
});
writeFileSync(
  "mcp/dist/THIRD_PARTY_NOTICES.md",
  [
    "# Third-party notices for the bundled files in mcp/dist",
    "",
    "Generated by scripts/bundle.mjs. Components downloaded at runtime are listed in",
    "THIRD_PARTY_NOTICES.md at the repository root.",
    "",
    ...sections.flatMap((section) => [section, ""]),
  ].join("\n"),
);
