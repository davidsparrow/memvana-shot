// Bundles the MCP server and CLI into self-contained files under mcp/dist/.
// The bundles are committed: plugins install by git clone, with no build step.
// They are minified (zod alone is ~1 MB unminified); read mcp/src instead.
// CI rebuilds and fails if the committed bundles differ from the source.
import { build } from "esbuild";

await build({
  entryPoints: { server: "mcp/src/bin/server.ts", cli: "mcp/src/bin/cli.ts" },
  outdir: "mcp/dist",
  outExtension: { ".js": ".mjs" },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify: true,
  legalComments: "none",
  logLevel: "info",
  banner: {
    js: [
      "// Generated by scripts/bundle.mjs from mcp/src. Do not edit.",
      "import { createRequire as __createRequire } from 'node:module';",
      "const require = __createRequire(import.meta.url);",
    ].join("\n"),
  },
});
